package setupwizard

import (
	"fmt"
	"strings"
	"time"

	"github.com/msch128/mnema-talk/internal/config"
)

// Secrets are the generated values.
type Secrets struct {
	JWT, Postgres, S3Access, S3Secret, AdminPassword, UpdaterToken string
}

// NewSecrets generates a fresh set.
func NewSecrets() Secrets {
	return Secrets{
		JWT:           config.RandomHex(32),
		Postgres:      config.RandomHex(16),
		S3Access:      "mnema" + config.RandomHex(5),
		S3Secret:      config.RandomHex(24),
		AdminPassword: config.RandomHex(12),
		UpdaterToken:  config.RandomHex(32),
	}
}

// publishAddr is what the compose file publishes the app port on. Behind a
// TLS reverse proxy on the same host loopback is enough and keeps plain HTTP
// off the network; without TLS the app is reached directly.
func publishAddr(o Options) string {
	if strings.HasPrefix(o.PublicURL, "https://") || o.IsLocal() {
		return "127.0.0.1"
	}
	return "0.0.0.0"
}

// RenderEnv returns the content of the generated .env. Only values that must
// be set are active; everything optional is a commented hint, so the file
// stays short and a later reader sees what was decided.
func RenderEnv(o Options, s Secrets, now time.Time) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by `mnema-talk setup` on %s. Keep this file private (chmod 600).", now.UTC().Format("2006-01-02"))
	w("# Only what you must or may change is listed; every other setting has a")
	w("# default. The full list is in doc/operations.md.")
	w("")
	w("# --- The address members open (the one thing you have to get right) ---")
	w("# Origins, cookies, invite links and e-mail links follow from it.")
	w("PUBLIC_URL=%s", o.PublicURL)
	w("MNEMA_IMAGE=%s", o.Image)
	w("INITIAL_LANGUAGE=%s", o.Language)
	w("ADMIN_USERNAME=%s", o.AdminUsername)
	w("")
	w("# --- Secrets, generated for this installation ---")
	w("# Do not change POSTGRES_PASSWORD, S3_ACCESS_KEY or S3_SECRET_KEY after the")
	w("# first start: the database and the object store keep the values they began with.")
	w("JWT_SECRET=%s", s.JWT)
	w("POSTGRES_PASSWORD=%s", s.Postgres)
	w("S3_ACCESS_KEY=%s", s.S3Access)
	w("S3_SECRET_KEY=%s", s.S3Secret)
	w("# Password of the Owner account for the first sign-in; delete this line afterwards.")
	w("ADMIN_INITIAL_PASSWORD=%s", s.AdminPassword)
	w("")
	w("# --- Network ---")
	w("PUBLISH_ADDR=%s", publishAddr(o))
	if o.AppPort() != defaultAppPort {
		w("PORT=%s", o.AppPort())
	}
	w("# Reverse proxy not on this host? Name its address (never a whole range):")
	w("# TRUSTED_PROXY_CIDRS=172.17.0.1")
	w("# Voice: the public IPv4 address is found at startup with a STUN request.")
	w("# Pin it (or give a dynamic-DNS name) if that is wrong or you want no lookup:")
	w("# WEBRTC_NAT_1TO1_IP=203.0.113.7")
	w("# WEBRTC_AUTO_ANNOUNCE=false")
	w("# This host's address in your own network, announced next to the public one so")
	w("# members at home reach voice although the router cannot loop back to itself:")
	if o.LANIP != "" {
		w("WEBRTC_LAN_IP=%s", o.LANIP)
	} else {
		w("# WEBRTC_LAN_IP=192.168.1.20")
	}
	w("# Members behind networks that block UDP connect through the built-in TURN relay")
	w("# on port 3479 (UDP and TCP; forward it like the voice ports). It is off while")
	w("# WEBRTC_TURN_URLS names an external TURN server. Switch it: auto (default), on, off.")
	w("# WEBRTC_BUILTIN_TURN=auto")
	w("# WEBRTC_BUILTIN_TURN_PORT=3479")
	w("")
	renderMail(w, o.SMTP)
	if o.AutoUpdate {
		w("")
		w("# --- 'Update now' button in the admin console (updater sidecar) ---")
		w("COMPOSE_PROFILES=autoupdate")
		w("UPDATER_TOKEN=%s", s.UpdaterToken)
	}
	return b.String()
}

func renderMail(w func(string, ...any), s SMTP) {
	w("# --- Outgoing e-mail (password reset, address confirmation) ---")
	if !s.Enabled() {
		w("# SMTP_HOST=smtp.example.org")
		w("# SMTP_PORT=587")
		w("# SMTP_TLS=starttls")
		w("# SMTP_USERNAME=")
		w("# SMTP_PASSWORD=")
		w("# SMTP_FROM=Mnema Talk <noreply@example.org>")
		return
	}
	w("SMTP_HOST=%s", s.Host)
	if s.Port != "" {
		w("SMTP_PORT=%s", s.Port)
	}
	if s.TLS != "" {
		w("SMTP_TLS=%s", s.TLS)
	}
	if s.Username != "" {
		w("SMTP_USERNAME=%s", s.Username)
		w("SMTP_PASSWORD=%s", quoteEnv(s.Password))
	}
	w("SMTP_FROM=%s", quoteEnv(s.From))
}

// quoteEnv quotes a value when it holds characters Docker Compose's .env
// parser would treat specially.
func quoteEnv(v string) string {
	if !strings.ContainsAny(v, " #$\"'\\`<>") {
		return v
	}
	if !strings.Contains(v, "'") {
		return "'" + v + "'"
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`).Replace(v) + `"`
}
