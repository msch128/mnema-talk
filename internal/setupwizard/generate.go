package setupwizard

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

// templatePaths are searched, in order, for the docker-compose.yml to derive
// the generated one from: the copy inside the image, then the current
// directory (a checkout or a downloaded release).
var templatePaths = []string{"/usr/share/mnema/docker-compose.yml", "docker-compose.yml"}

// buildBlock matches the build-from-source part of the app service, up to
// and including its image line.
var buildBlock = regexp.MustCompile(`(?s)    build:\n.*?    image: \$\{MNEMA_IMAGE:-mnema-talk:local\}\n`)

const localImageDefault = "${MNEMA_IMAGE:-mnema-talk:local}"

// RenderCompose derives the compose file for a released image from the
// repository's: no build section, the image default points at the registry.
// The settings stay in .env, so the file itself needs no editing.
func RenderCompose(template []byte, image string) ([]byte, error) {
	s := string(template)
	if !buildBlock.MatchString(s) {
		return nil, errors.New("the compose template has no build section to replace: it does not look like Mnema Talk's docker-compose.yml")
	}
	def := "${MNEMA_IMAGE:-" + image + "}"
	s = buildBlock.ReplaceAllLiteralString(s, "    # The released image; MNEMA_IMAGE in .env picks the tag.\n    # Update: docker compose pull && docker compose up -d\n    image: "+def+"\n")
	s = strings.ReplaceAll(s, localImageDefault, def)
	header := "# Generated by `mnema-talk setup`. Settings live in .env: edit that, not this file.\n# Documentation: doc/deployment.md\n"
	return []byte(header + s), nil
}

// readTemplate loads the compose template from path, or from the default
// locations when path is empty.
func readTemplate(path string) ([]byte, error) {
	candidates := templatePaths
	if path != "" {
		candidates = []string{path}
	}
	for _, p := range candidates {
		if b, err := os.ReadFile(p); err == nil {
			return b, nil
		}
	}
	return nil, fmt.Errorf("docker-compose.yml template not found (looked in %s): pass --compose-template or download it from https://github.com/msch128/mnema-talk", strings.Join(candidates, ", "))
}

// Generated reports what Write created.
type Generated struct {
	EnvPath, ComposePath string
	Secrets              Secrets
}

// Dir is the directory the files were written to.
func (g Generated) Dir() string { return filepath.Dir(g.EnvPath) }

// Write creates .env (mode 0600) and docker-compose.yml in o.Dir. Existing
// files are never replaced without Force: a new .env holds new secrets, and
// a database or object store created with the old ones would refuse them.
func Write(o Options, template []byte, s Secrets, now time.Time) (Generated, error) {
	o, err := o.normalize()
	if err != nil {
		return Generated{}, err
	}
	compose, err := RenderCompose(template, o.Image)
	if err != nil {
		return Generated{}, err
	}
	g := Generated{EnvPath: filepath.Join(o.Dir, ".env"), ComposePath: filepath.Join(o.Dir, "docker-compose.yml"), Secrets: s}
	if !o.Force {
		for _, p := range []string{g.EnvPath, g.ComposePath} {
			if _, err := os.Stat(p); err == nil {
				return Generated{}, fmt.Errorf("%s already exists and was left alone; to start over (this generates new secrets, which an existing database will not accept) remove it or pass --force", p)
			}
		}
	}
	if err := os.MkdirAll(o.Dir, 0o755); err != nil {
		return Generated{}, err
	}
	if err := writeFile(g.EnvPath, []byte(RenderEnv(o, s, now)), 0o600); err != nil {
		return Generated{}, err
	}
	return g, writeFile(g.ComposePath, compose, 0o644)
}

func writeFile(path string, data []byte, mode fs.FileMode) error {
	if err := os.WriteFile(path, data, mode); err != nil {
		if errors.Is(err, fs.ErrPermission) {
			return fmt.Errorf("%w: the directory is not writable for this user; run the container with --user \"$(id -u):$(id -g)\" (or on a NAS as root)", err)
		}
		return err
	}
	return os.Chmod(path, mode)
}
