export function isTextDefaultEmoji(cp: number): boolean {
  return TEXT_DEFAULT.some(([lo, hi]) => cp >= lo && cp <= hi)
}

/** What makes two reactions one: the emoji without U+FE0F. */
export function reactionKey(emoji: string): string {
  return emoji.replaceAll(EMOJI_SELECTOR, '')
}

function takesEmojiSelector(ch: string, next: string | undefined): boolean {
  const n = next?.codePointAt(0) ?? 0
  if (next === TEXT_SELECTOR || (n >= 0x1f3fb && n <= 0x1f3ff)) return false
  if (ch === '#' || ch === '*' || (ch >= '0' && ch <= '9')) return next === KEYCAP
  return isTextDefaultEmoji(ch.codePointAt(0) ?? 0)
}

/** The one form a reaction is sent and shown in: the fully-qualified emoji of
 * Unicode (U+FE0F after exactly the characters shown as text by default). A
 * custom emoji token stays as it is. */
export function reactionForm(emoji: string): string {
  if (parseEmojiToken(emoji)) return emoji
  const chars = [...reactionKey(emoji)]
  return chars.map((ch, i) => (takesEmojiSelector(ch, chars[i + 1]) ? ch + EMOJI_SELECTOR : ch)).join('')
}
